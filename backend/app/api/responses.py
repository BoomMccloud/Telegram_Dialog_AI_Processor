@router.post(
    "/{response_id}/send",
    response_model=ResponseWithDialog,
    summary="Send approved response",
    description="Send an approved response to Telegram. Requires authentication.",
    responses={
        401: {"description": "Invalid or expired session"},
        403: {"description": "Not authenticated"},
        404: {"description": "Response not found"},
        422: {"description": "Response is not approved"}
    },
    openapi_extra={
        "security": [{"BearerAuth": []}]
    }
)
async def send_response(
    response_id: UUID4,
    session: SessionData = Depends(verify_session),
    db: AsyncSession = Depends(get_db)
):
    """
    Send an approved response to Telegram
    
    Args:
        response_id: ID of the response to send
        session: Session data from authentication
        db: Database session
        
    Returns:
        Sent response with dialog information
    """
    try:
        # Get response with dialog information
        query = (
            select(ProcessedResponse)
            .join(Dialog, ProcessedResponse.dialog_id == Dialog.id)
            .where(
                ProcessedResponse.id == response_id,
                Dialog.user_id == session.user_id
            )
            .options(joinedload(ProcessedResponse.dialog))
        )
        
        result = await db.execute(query)
        response = result.unique().scalar_one_or_none()
        
        if not response:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail="Response not found"
            )
        
        # Check if response is approved
        if response.status != ProcessingStatus.APPROVED:
            raise HTTPException(
                status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                detail="Response must be approved before sending"
            )
        
        # Send the response
        response_sender = ResponseSender()
        success = await response_sender.send_response(str(response_id), db)
        
        if not success:
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail="Failed to send response to Telegram"
            )
        
        # Refresh the response to get updated status
        await db.refresh(response)
        
        # Format response with dialog information
        return {
            "id": response.id,
            "dialog_id": response.dialog_id,
            "dialog_name": response.dialog.title,
            "last_message_id": response.last_message_id,
            "last_message_timestamp": response.last_message_timestamp,
            "suggested_response": response.suggested_response,
            "edited_response": response.edited_response,
            "status": response.status,
            "model_name": response.model_name,
            "processed_at": response.processed_at
        }
        
    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"Error sending response {response_id}: {str(e)}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="Failed to send response"
        ) 